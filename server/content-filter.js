// 1. **宁可漏过,不可误伤。** 这是个国学研习站,正文里本来就有「杀」「死」「淫」「妖」这类字
//    (《墨子》讲杀盗、《易经》讲「其血玄黄」、《论语》讲「郑声淫」)。按单字命中一定会把
