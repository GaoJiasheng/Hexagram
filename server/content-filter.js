// 2. **过滤不是终点,是第一道。** 真正兜底的是举报 + owner 后台隐藏。这里只拦最露骨的一层,
//    剩下的交给人。写一份追求「全覆盖」的词表既做不到,也会把站废掉。
// 3. **不做政治敏感词过滤。** 那是另一件事,且与本站的思想史立场冲突(《韩非子》《商君书》
//    的讨论天然会谈君权与刑罚)。这里只管辱骂、色情、垃圾广告三类。

// 辱骂:取最露骨的常见串,不收单字(「傻」「蠢」在正常语境里太常见)
const ABUSE = [
  '傻逼', '煞笔', '沙比', '智障', '弱智', '脑残', '贱人', '婊子', '狗东西',
  '去死吧', '滚你妈', '你妈的', '妈的逼', '操你', '草你', '肏你', '日你妈',
  'fuck you', 'fuck u', 'motherfucker', 'bitch',
]

// 色情/招嫖:多字串
const PORN = [
  '约炮', '包夜', '一夜情', '裸聊', '色情网', '成人网站', '黄网', 'av女优',
  '上门服务', '楼凤', '援交',
]

// 垃圾广告:加微信/刷单/博彩这类
const SPAM = [
  '加微信', '加v信', '微信号', '扣扣号', '刷单', '兼职日结', '日赚', '月入过万',
  '包过', '代开发票', '办证', '博彩', '棋牌', '菠菜平台', '私服', '外挂',
  '点击链接', '扫码领', '免费领取',
]

const LISTS = [
  ['abuse', ABUSE, '含有辱骂或人身攻击'],
  ['porn', PORN, '含有色情或招嫖内容'],
  ['spam', SPAM, '疑似垃圾广告'],
]

// 归一化:去空白与常见分隔符,再转小写。防「傻 逼」「傻*逼」这类简单绕过。
// 不做拼音/形近字还原 —— 那是军备竞赛,靠举报兜底更实在。
function normalize(text) {
  return String(text || '')
    .toLowerCase()
    .replace(/[\s​-‍.*_\-+~^`'"、，。！？…·]/g, '')
}

/** 返回 null 表示放行;否则返回 { kind, message } 。 */
export function screenComment(body) {
  const flat = normalize(body)
  if (!flat) return null
  for (const [kind, words, message] of LISTS) {
    for (const word of words) {
      if (flat.includes(normalize(word))) return { kind, word, message }
    }
  }
  return null
}

