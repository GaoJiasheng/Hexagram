// 母题:一段整齐的铅字,穿过一块屏幕,落下来变成一片散光点。
// 波兹曼的核心命题不是「电视上的东西不好」,而是:媒介的形式决定了什么样的内容
// 能被表达 —— 上面那几行是印刷术支持的东西(有先后、有主句从句、能一路论证到底),
// 下面那片是屏幕这个形式偏爱的东西(亮、快、彼此无关、看完即散)。
// 中间那道朱色的扫描线是屏幕自己:它不搬运内容,它筛选内容。
const CINNABAR = '#c3272b'

export default function TypeToGlow() {
  // 上方:六行铅字,长短不一,最后一行短 —— 一个段落的样子
  const lines = [
    { y: 58, x: 56, w: 188 },
    { y: 76, x: 56, w: 172 },
    { y: 94, x: 56, w: 192 },
    { y: 112, x: 56, w: 154 },
    { y: 130, x: 56, w: 180 },
    { y: 148, x: 56, w: 98 },
  ]
  // 下方:同样的东西出来之后 —— 散点,越往下越散、越暗
  const motes = [
    [96, 330, 2.6, 0.30], [128, 322, 1.6, 0.22], [158, 334, 3.0, 0.34],
    [188, 324, 1.8, 0.24], [214, 336, 2.2, 0.26], [74, 344, 1.4, 0.18],
    [110, 352, 2.0, 0.24], [144, 348, 1.5, 0.20], [176, 356, 2.4, 0.26],
    [206, 350, 1.6, 0.20], [238, 344, 2.0, 0.22], [60, 366, 1.8, 0.16],
    [92, 372, 1.3, 0.16], [126, 368, 2.2, 0.20], [160, 376, 1.5, 0.16],
    [194, 370, 1.9, 0.18], [226, 378, 1.4, 0.14], [252, 366, 1.7, 0.16],
    [48, 388, 1.4, 0.12], [82, 394, 1.9, 0.14], [118, 390, 1.3, 0.12],
    [152, 398, 1.6, 0.13], [186, 392, 1.2, 0.11], [220, 398, 1.8, 0.13],
    [254, 390, 1.3, 0.11], [40, 352, 1.2, 0.12], [270, 356, 1.4, 0.12],
  ]
  return (
    <g>
      {/* 铅字:整齐、有行、有先后 */}
      {lines.map((l) => (
        <rect
          key={l.y}
          x={l.x}
          y={l.y}
          width={l.w}
          height="2.4"
          rx="1.2"
          fill="rgba(255,255,255,0.30)"
        />
      ))}

      {/* 收口:一切都得从这个口子过去 */}
      <path d="M56,166 L92,208" stroke="rgba(255,255,255,0.14)" strokeWidth="1" fill="none" />
      <path d="M244,166 L208,208" stroke="rgba(255,255,255,0.14)" strokeWidth="1" fill="none" />

      {/* 屏幕外的一圈微光 */}
      <rect x="78" y="202" width="144" height="106" rx="18" fill="rgba(255,255,255,0.05)" />
      {/* 屏幕 */}
      <rect x="86" y="210" width="128" height="90" rx="13" fill="rgba(0,0,0,0.26)" />
      <rect
        x="86"
        y="210"
        width="128"
        height="90"
        rx="13"
        fill="none"
        stroke="rgba(255,255,255,0.42)"
        strokeWidth="1.4"
      />
      {/* 屏幕里的光:一片朱色,没有形状 */}
      <rect x="94" y="218" width="112" height="74" rx="9" fill={CINNABAR} opacity="0.20" />
      {/* 那道扫描线:它才是真正在做筛选的东西 */}
      <rect x="94" y="252" width="112" height="2.6" rx="1.3" fill={CINNABAR} opacity="0.92" />

      {/* 出来之后:散点 */}
      {motes.map(([cx, cy, r, o]) => (
        <circle key={`${cx}-${cy}`} cx={cx} cy={cy} r={r} fill="rgba(255,255,255,1)" opacity={o} />
      ))}
      {/* 其中几点仍是亮的 —— 但彼此不再有关系 */}
      <circle cx="140" cy="340" r="2.4" fill={CINNABAR} opacity="0.72" />
      <circle cx="204" cy="384" r="1.9" fill={CINNABAR} opacity="0.55" />
    </g>
  )
}
