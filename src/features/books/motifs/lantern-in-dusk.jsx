// 母题:灯火阑珊。《人间词话》最著名的那一节,把辛弃疾《青玉案·元夕》的
// 「众里寻他千百度，蓦然回首，那人却在，灯火阑珊处」立为第三种境界 ——
// 前两境是「独上高楼，望尽天涯路」与「衣带渐宽终不悔」,都在苦寻;
// 到这一境,寻的人停下、回过头,要找的东西原来在灯火将尽、人声散去的地方。
//
// 所以画面不画热闹:上半是一片朦胧散开的灯(白,渐远渐淡),
// 唯有偏在一侧、离众灯最远的那一盏是朱的 —— 它不亮,但只有它是「那人」。
// 下方一道水痕把众灯映成倒影,倒影比灯本身更淡:词的境界正是这般
// 「不隔」而又隔了一层的东西。
const CINNABAR = '#c3272b'

export default function LanternInDusk() {
  // 众灯:自中上向两侧散开,越远越淡越小(热闹是背景,不是主角)
  // ⚠️ 版式约束:书名在封面**右侧竖排**(x 约 240–280),母题一切要素须避开那一带,
  // 否则朱色点睛会压在字上。故众灯整体偏左,阑珊那盏落在左下而非右下。
  const lamps = [
    [138, 116, 5.2, 0.30], [106, 124, 4.6, 0.26], [170, 122, 4.6, 0.26],
    [78, 138, 4.0, 0.20], [198, 136, 4.0, 0.20],
    [54, 156, 3.4, 0.15], [214, 154, 3.4, 0.15],
    [122, 146, 3.6, 0.18], [156, 148, 3.6, 0.18],
    [92, 166, 3.0, 0.13], [184, 164, 3.0, 0.13],
  ]
  // 阑珊处那一盏:离众灯最远、最小,却是画面里唯一有色的
  const HX = 74, HY = 212

  return (
    <g>
      {/* 天光下的一层薄雾,把众灯托住 */}
      <path d="M40 104 C110 88,190 88,262 106 L262 186 C190 172,110 172,40 188 Z"
        fill="rgba(255,255,255,0.05)" />

      {/* 众里寻他千百度 —— 灯多而朦胧 */}
      {lamps.map(([x, y, r, o], i) => (
        <g key={i}>
          <circle cx={x} cy={y} r={r * 2.6} fill="rgba(255,255,255,0.05)" />
          <circle cx={x} cy={y} r={r} fill="rgba(255,255,255,0.5)" opacity={o + 0.3} />
        </g>
      ))}

      {/* 蓦然回首 —— 一道自众灯折向阑珊处的目光 */}
      <path d="M138 130 C120 156,98 182,80 204"
        stroke="rgba(255,255,255,0.16)" strokeWidth="1" fill="none" strokeDasharray="3 5" />

      {/* 那人却在,灯火阑珊处 */}
      <circle cx={HX} cy={HY} r="13" fill={CINNABAR} opacity="0.14" />
      <circle cx={HX} cy={HY} r="7.5" fill={CINNABAR} opacity="0.28" />
      <circle cx={HX} cy={HY} r="3.6" fill={CINNABAR} opacity="0.95" />

      {/* 水痕:倒影比灯更淡 —— 境界是隔着一层看见的 */}
      <path d="M34 262 L266 262" stroke="rgba(255,255,255,0.24)" strokeWidth="1.1" fill="none" />
      {lamps.slice(0, 5).map(([x, y, r], i) => (
        <ellipse key={`r${i}`} cx={x} cy={262 + (262 - y) * 0.20} rx={r * 0.8} ry={r * 0.32}
          fill="rgba(255,255,255,0.13)" />
      ))}
      <ellipse cx={HX} cy={262 + (262 - HY) * 0.20} rx="3" ry="1.3" fill={CINNABAR} opacity="0.34" />

      {/* 水下的暗,压住下半幅 */}
      <path d="M34 262 C110 270,190 270,266 262 L266 326 C190 340,110 340,34 326 Z" fill="rgba(0,0,0,0.16)" />
    </g>
  )
}
